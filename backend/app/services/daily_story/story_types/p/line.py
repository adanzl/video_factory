"""日常故事 P 类线路（整蛊互整）。"""

from app.services.daily_story.story_types.model import (
    STORY_TYPE_KEYWORDS,
    StoryTypeLine,
    compile_layers,
)

LINE_P = StoryTypeLine(
    code="P",
    label="整蛊互整",
    keywords=STORY_TYPE_KEYWORDS["P"],
    quality_ready=False,
    body_lines_min=10,
    body_lines_max=18,
    line_format_hint="8–14字，下料/硬撑/回敬/认怂各一句，禁空慌",
    punchline_example="P类整蛊互整，以牙还牙后认输散场",
    prompt_block="""\
【本次类型：P 整蛊互整 — 专属线路】
- 核心：一方用**道具/动作**下料或立挑战 → 对方硬撑或自食其果
  → **回敬加码**（以牙还牙）→ **认输/散场**（可笑散，非真情 pivot）。
- **不是** F 互呛加码：主升的是道具整蛊，不是口头威胁/吼叫气势。
- **不是** C 公平执念：不争同一物归谁、不写双规则赛规、末句勿回旋镖戳穿。
- **不是** G 嘴硬心软：无护短/擦药真心破防；散场只是挑战结束。
- **不是** O 目标错位：不是顾过程丢目标，是互整后一方怂。
- **不是** J 权威压住：无单方否决/一锤镇场，须双向回敬。

【四段链（顺序固定；收束多样）】
1 **下料/挑战**（2–4 句）：递物、声称好吃/无害、怂恿尝尝。
2 **硬撑或自食**（2–4 句）：被整方硬撑，或整人方自己也中招。
3 **回敬加码**（2–4 句）：对方递回加料/再开一局，须可见升级。
4 **认怂散场**（1–3 句）：认输/不敢再试；可短笑散或分吃剩余；
   禁止 C 回旋镖、A 末四拍、G 暖收、F 纯威胁僵持当主戏。

【硬约束】
- 主戏姐弟；妈妈宜 0–1 句。
- 中段须**道具/动作升级**，勿车轱辘同一句互呛复读。
- **认怂方=挑战发起人**（首发下料方）；禁止后半逆袭颠倒。
- key/punchline **禁止**写回旋镖；对白须可说出口，禁分镜旁白。
""",
    user_closing="""\
收束须认怂或笑散；勿 C 回旋镖、G 暖收、F 纯口头威胁僵持、A 破功。""",
    body_user_anchor="先写下料挑战，再硬撑/自食，再回敬加码，最后认输散场。",
    opening_system_append="""\
P 类开场：可从挑战/递物起句，勿写成 C 争物公平或 F 纯互呛开吵。""",
    opening_user_append="开场到「刚递物/刚开挑战」，回敬与认怂留正文。",
    theme_user_append="主题宜道具整蛊互整（挑战/加料/回敬），非公平赛规或口头威胁链。",
    retry_soft_close_hint="补回敬加码+认怂散场；勿套 C/F/G/A 收束。",
    escalation_revision_hint="中段须道具回敬升级，勿只口头互呛不加码。",
    closing_revision_hint="收束须认输/不敢再试或短笑散；勿 C 回旋镖、G 擦药暖收。",
    layer_patterns=compile_layers(
        (
            ("P1_下料", r"尝尝|试试|给你|这卷|这口|挑战|香了|不辣|加料"),
            ("P2_硬撑自食", r"还行|没事|硬撑|呛|灌水|脸.*绿|眼泪"),
            ("P3_回敬", r"再试试|也给你|轮到你|特意|回敬|加了"),
            ("P4_认怂", r"认输|不了不了|不敢再|算了|我怂|服了"),
        ),
    ),
)
