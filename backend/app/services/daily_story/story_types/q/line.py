"""日常故事 Q 类线路（耍赖翻车）。"""

from app.services.daily_story.story_types.model import (
    STORY_TYPE_KEYWORDS,
    StoryTypeLine,
    compile_layers,
)

LINE_Q = StoryTypeLine(
    code="Q",
    label="耍赖翻车",
    keywords=STORY_TYPE_KEYWORDS["Q"],
    quality_ready=False,
    body_lines_min=10,
    body_lines_max=18,
    line_format_hint="8–14字，耍赖/拆穿/反噬各一句，禁空慌",
    punchline_example="Q类耍赖翻车，孩子借口被拆穿后反噬收场",
    prompt_block="""\
【本次类型：Q 耍赖翻车 — 专属线路】
- 核心：立玩法/约定后，孩子**耍赖或借口加码** → **被拆穿**
  → **赖法反噬**收场（加活/当场露馅等）。拆穿方可家长或姐弟，不锁家长。
- **对仗 E 妈妈破功**：E 是大人立论被孩子绕穿；Q 是孩子耍赖被拆穿后翻车。
- **不是** E：末句不是妈妈唉/破功；是孩子的赖被拆穿、反噬落在孩子侧。
- **不是** P 整蛊互整：无道具下料→回敬→认怂链。
- **不是** H 第三方化解：不是劝和拉手，是拆穿+反噬。
- **不是** C 公平执念：无双规则同场回旋镖。

【四段链（顺序固定；收束多样）】
1 **立玩法/约定**（2–3 句）：抽签/轮流/谁多谁少等可拍约定。
2 **耍赖或借口加码**（3–5 句）：重抽、逞强、推锅、借口少吃等。
3 **被拆穿**（2–3 句）：点破小心思/旧账/自相矛盾；须有拆穿方发言。
4 **反噬收场**（1–3 句）：赖法反打到自己（加活/吃瘪/当场认栽），
   禁止只写「自己噎住」无拆穿方；禁止套 E 妈妈破功、P 认怂互整。

【硬约束】
- 主戏可亲子或姐弟；妈妈若出场宜作拆穿/收场，勿写成旁观失败（K）或劝和（H）。
- 须同时有「耍赖加码 + 被拆穿 + 反噬」；缺拆穿方的自食其果不算 Q。
- **角色硬锁**：conflict/seed 标明的耍赖孩子=唯一耍赖方；
  重抽/逞强/胃小推食/借口等第一人称句**只能由耍赖方说**；
  新增姐弟只拆穿质疑，禁止抢耍赖方借口与推食。
- 妈妈反噬宜点明与前面借口的因果（须回指胃小/推食等）；
  禁垫字尾巴与多尾音叠堆；拆穿接话禁复读；
  逞强后须有示弱/改口再推食；拆穿具体事实须有前文铺垫。
- key/punchline 以「Q类耍赖翻车」开头；对白可说出口，禁分镜旁白。
""",
    user_closing="""\
收束须拆穿后反噬落在耍赖方；勿 E 妈妈破功、P 互整认怂、H 劝和。""",
    body_user_anchor="先立玩法，再写耍赖/借口，再被拆穿，最后反噬收场。",
    opening_system_append="""\
Q 类开场：可从玩法/约定起句，勿写成 E 妈妈立论被追问或 P 递物挑战。""",
    opening_user_append="开场到「刚立约定/刚开耍」，拆穿与反噬留正文。",
    theme_user_append="主题宜耍赖/借口被拆穿翻车，非互整认怂或妈妈破功。",
    retry_soft_close_hint="补拆穿+反噬收场；勿套 E/P/H/C。",
    escalation_revision_hint="中段须可见耍赖加码，勿只复读同一句。",
    closing_revision_hint="收束须被拆穿后反噬；勿 E 破功、P 认怂、H 和好。",
    layer_patterns=compile_layers(
        (
            ("Q1_立约定", r"抽签|轮到|几口|约定|谁.*谁|规则|玩法"),
            ("Q2_耍赖加码", r"耍赖|重抽|再抽|逞强|借口|推给|胃小|太少|不认"),
            ("Q3_拆穿", r"看穿|拆穿|揭穿|心思|你昨天|偷|别装|露馅"),
            ("Q4_反噬", r"洗碗|刷碗|加活|罚|活该|自己.*收拾|你去|翻车"),
        ),
    ),
)
