    # 句数硬预算：21–24 句 × 每句 8–14 字核心（急喊/甩锅可短至 4–6 字）
    # 隐含约 240–340 字；拼接时正文开头与开场重叠的密谋句会被删掉（约 30 字），
    # 故首稿瞄准 250–300，删后仍 ≥240 落在硬卡内
    body_lines_min=21,
