"""日常故事 C 类线路（提示词片段）。"""

from app.services.daily_story.story_types.model import (
    STORY_TYPE_KEYWORDS,
    StoryTypeLine,
    compile_layers,
)

LINE_C = StoryTypeLine(
    code="C",
    label="公平执念",
    keywords=STORY_TYPE_KEYWORDS["C"],
    quality_ready=True,
    punchline_example="C类公平执念，姐姐规则被字面戳穿",
    prompt_block="""\
【本次类型：C 公平执念 — 专属线路】
- 公式：双方抢同一资源→各自抛对己有利的规则→规则互相冲突
  （你先拿 vs 我先看 / 你切你选 vs 你拿你就选了）
  →一方规则被字面执行反噬或两套规则产生荒谬结论→收束。
- 笑点：每个人在「自己的规则下」都对，两套公平标准无法兼容。

【节奏·升级路线（C 专用，须逐步推进）】
1 争归属（谁先碰/谁的）→ 2 挑战规则（你的规则不算）
→ 3 挑战权威（凭什么你定）→ 4 量化/加赛证据 → 5 回旋镖收束
每一层最多 2 个来回；超过须立刻进下一层；后半程须进入 4、5 层。

【前 8 句·必做】
- 前 8 句内抛出一条可执行赛规（谁碰谁负责、谁更急谁先、切的人先选等），
  勿拖到后半才立规矩。
- 「归谁/都是我的/你没叠我叠了没」同一逻辑最多 2 来回，禁止中段口水战。

【中段好笑·字面加赛（C 专用）】
- 赛规立住后，用可拍动作按对方规则加赛（多喝一口、多拿一杯、
  故意叠乱再递给对方收、让自己更急/更占优等），形成孩子气的荒谬较真。
- 全篇同一赛规只立一次；中段争法升级最多 4 个来回，然后必须进末四拍。
- 禁止只靠「指一下/不算/那不一样」口头诡辩撑满末段。

【笑点与收束（C 专用）】
- 优先回旋镖：用对方刚立的规则原路反问（你说的/你刚说+原话子串），
  逼出自相矛盾。
- 收束前须有一件看得见的争法动作或状态变化，再扣赛规；勿写成 A 式
  「那不一样」「哪里不一样」末四拍。
- 末句须破功方（被戳穿/嘴硬）说最后一句，禁止赢家总结陈词。
- 赛规全文须自洽：后文字面执行须能扣回前文同一条规则。

【单句≤22字（硬性）】
- 每句一条意思；引赛规用短称（如「谁弄乱谁收拾」），勿整段复读。
- 每句须写完整，以。！？或哼/行吧/认了等结束，禁止写到引号一半停下。
""",
    user_closing="""\
9. 【C类收束模板·必遵守】末尾 4 句（[规则]替换成当前争论的那条公平标准）：
   倒数第4句：一方按赛规做出可见动作或加赛（须扣主题实物/动作）
   倒数第3句：对方喊耍赖/作弊/不算（情绪顶一下）
   倒数第2句：用对方刚说的规则反问（你刚说/你说的+短规则名，须写完整一句）
   末句：被戳穿方嘴硬收场（"……哼/……行/……随便"），必须破功方说最后一句
""",
    layer_patterns=compile_layers(
        [
            (
                "C1_争归属",
                r"凭什么.*拿|怎么在.*你手|我先|归谁|凭什么.*你的|你抢|"
                r"应该给我|谁先",
            ),
            (
                "C2_挑战规则",
                r"谁说的|没说过|不算|你定的|你刚说|你编的|规矩|"
                r"谁说|又不是你定的|规则是你|反悔|变来变去|"
                r"说话不算|凭什么.*定|你说的不算|你自己.*又说",
            ),
            (
                "C3_挑战权威",
                r"凭什么你|你说了算|你又不是|你是姐姐|你凭什么|"
                r"不是.*说了算|又不是你|你定.*不算|我比你大|我是姐姐",
            ),
            (
                "C4_新证据",
                r"上次|之前|妈妈说过|爸爸.*说|说过什么|你再想想|"
                r"记得.*说|上次.*规则|柜子里|里面还有|等等.*说|"
                r"一件|一条|半杯|十分钟|数.{0,4}(?:下|件)|"
                r"比.{0,6}(?:急|久|多|乱)|叠.{0,6}(?:整齐|马虎|好)",
            ),
            (
                "C5_收束",
                r"那.*你还|我不要|我才不|说不过|反正我|就是|不管了|"
                r"给你|那给你|下次.*算|哼|算了算了|归我|归你|自相矛盾|嘴硬",
            ),
        ],
    ),
    escalation_revision_hint=(
        "【C·冲突升级】前 8 句内立清一条赛规；删「归谁/你没叠」多轮口水；"
        "插入 2–4 句量化争法或字面加赛（按赛规夸张执行），再进收束。"
    ),
    closing_revision_hint=(
        "【C·收束】末 4 句：可见加赛动作→对方喊不算→你说的+赛规回旋镖→"
        "破功方哼/行；禁止「那不一样」「哪里不一样」。"
    ),
    retry_soft_close_hint=(
        "【C·收束】末句破功方嘴硬（哼/给你/算了），"
        "前一句须回旋镖扣对方刚立的赛规，勿 A 式那不一样。"
    ),
)

